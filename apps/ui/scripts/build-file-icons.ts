// Bundles the Material Icon Theme icons that src/components/fileIcons/names.ts maps files to into
// src/components/fileIcons/svgs.ts, so the app ships only those instead of the whole set. The result
// is committed; rerun this after changing the mapping:
//
//   bun run --cwd apps/ui icons

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

import { iconNames } from "../src/components/fileIcons/names.ts";

interface IconSet {
  readonly icons: Readonly<Record<string, { body: string; width?: number; height?: number }>>;
  readonly aliases?: Readonly<Record<string, { parent: string }>>;
}

const require = createRequire(import.meta.url);
const set = JSON.parse(
  readFileSync(require.resolve("@iconify-json/material-icon-theme/icons.json"), "utf8"),
) as IconSet;

const svg = (name: string): string => {
  const icon = set.icons[name] ?? set.icons[set.aliases?.[name]?.parent ?? ""];
  if (icon === undefined) throw new Error(`Material Icon Theme has no icon named "${name}".`);
  // Iconify's default box is 16 units square.
  const width = icon.width ?? 16;
  const height = icon.height ?? 16;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}">${icon.body}</svg>`;
};

const entries = [...iconNames()]
  .sort()
  .map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(svg(name))},`);

writeFileSync(
  join(import.meta.dirname, "..", "src", "components", "fileIcons", "svgs.ts"),
  `// Generated by scripts/build-file-icons.ts from @iconify-json/material-icon-theme (MIT, Material
// Extensions). Do not edit; change names.ts and rerun the script.

export const svgs: Readonly<Record<string, string>> = {
${entries.join("\n")}
};
`,
);
console.log(`Wrote ${entries.length} icons.`);
