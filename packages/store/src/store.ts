/** The SQL migrations generated by drizzle-kit, one folder each, next to this package's sources. */
export const defaultMigrationsFolder = join(import.meta.dirname, "..", "migrations");

/** Streamed text: the cloud copy keeps the completed message instead (`isStreamDelta`). */
const STREAM_DELTAS = ["MessageDelta", "ReasoningDelta"];

/**
 * An event's columns but `raw`, which nothing reads back: it is often twice the size of the payload
 * (a screenshot's bytes, again), and parsing it made reading a thread several times slower.
 */
const eventColumns = {
  id: events.id,
  threadId: events.threadId,
  agentId: events.agentId,
  sequence: events.sequence,
  at: events.at,
  payload: events.payload,
};

export class StoreError extends Schema.TaggedError<StoreError>()("StoreError", {
  message: Schema.String,
  cause: Schema.Defect(),
}) {}

/** `effort: null` clears the effort, for a model its harness offers no effort setting for. */
export type AgentPatch = Partial<Pick<AgentInfo, "state" | "provider" | "model" | "autoEffort">> & {
  readonly effort?: AgentInfo["effort"] | null;
  /** `null` forgets the session, as handing the agent to another harness does. */
  readonly providerSessionId?: string | null;
  readonly updatedAt: number;
};

/** `archivedAt: null` restores an archived thread; `laterUntil: null` brings one put off back now. */
export interface ThreadPatch {
  readonly title?: string;
  readonly archivedAt?: number | null;
  readonly laterUntil?: number | null;
}

export interface StoredProject {
  readonly path: string;
  readonly addedAt: number;
  readonly usedAt: number;
  /** The user's setup command here; null defers to the project's own `.cerium.toml`. */
  readonly setup: string | null;
  /** The user's run command here; null defers to the project's own `.cerium.toml`. */
  readonly run: string | null;
}

/** A thread whose messages match a search, and the passage around its best match in pieces. */
export interface MessageMatch {
  readonly threadId: ThreadId;
  /** The matched words are the pieces marked `match`. */
  readonly passage: ReadonlyArray<{ readonly text: string; readonly match: boolean }>;
}

/**
 * What the spend report reads of one event: the turns' usage, and the events that say which model
 * those turns ran on. Counts are absent for any other event.
 */
export interface SpendEvent {
  readonly agentId: AgentId;
  readonly threadId: ThreadId;
  readonly at: number;
  readonly tag: "UsageReported" | "SessionStarted" | "ModelChanged" | "TurnInput";
  /** On `SessionStarted` and `ModelChanged`. */
  readonly model?: string;
  readonly inputTokens?: number;
  readonly outputTokens?: number;
  readonly cachedInputTokens?: number;
  readonly costUsd?: number;
}

/** How many words of a search count; the rest are ignored. */
const SEARCH_WORDS = 8;

/**
 * The full-text query for what the user typed: every word must start a word in the message, so
 * results narrow as they type. Each is quoted, so punctuation and the query syntax read as plain
 * text. None when nothing typed can match a word.
 */
export const searchExpression = (typed: string): string | undefined => {
  const words = typed
    // A control character, such as a pasted NUL, would end the quoted word early.
    .replaceAll(/\p{C}/gu, " ")
    .split(/\s+/u)
    .filter((word) => /[\p{L}\p{N}]/u.test(word))
    .slice(0, SEARCH_WORDS);
  return words.length === 0 ? undefined : words.map((word) => `"${word.replaceAll('"', '""')}"*`).join(" ");
};

// What `snippet()` puts around each matched word; neither turns up in typed text.
const MATCH_START = "\u0001";
const MATCH_END = "\u0002";

/** A snippet split into plain and matched pieces. */
const passageOf = (snippet: string): MessageMatch["passage"] =>
  snippet
    // oxlint-disable-next-line no-control-regex -- the markers are control characters on purpose
    .split(/(\u0001[^\u0002]*\u0002)/u)
    .filter((piece) => piece !== "")
    .map((piece) =>
      piece.startsWith(MATCH_START)
        ? { text: piece.slice(1, -1), match: true }
        : { text: piece.replaceAll(MATCH_END, ""), match: false },
    );

export class Store extends Context.Service<
  Store,
  {
    createThread(thread: ThreadInfo): Effect.Effect<void, StoreError>;
    getThread(id: ThreadId): Effect.Effect<Option.Option<ThreadInfo>, StoreError>;
    readonly listThreads: Effect.Effect<ReadonlyArray<ThreadInfo>, StoreError>;
    updateThread(id: ThreadId, patch: ThreadPatch): Effect.Effect<void, StoreError>;
    /** Deletes a thread with its agents and events, atomically. */
    deleteThread(id: ThreadId): Effect.Effect<void, StoreError>;
    /**
     * The threads of one mode whose messages, the user's or the agents', hold every word of `typed`
     * (`searchExpression`), best match first.
     */
    searchMessages(
      typed: string,
      options: { readonly mode: ThreadMode; readonly limit: number },
    ): Effect.Effect<ReadonlyArray<MessageMatch>, StoreError>;
    createAgent(agent: AgentInfo): Effect.Effect<void, StoreError>;
    updateAgent(id: AgentId, patch: AgentPatch): Effect.Effect<void, StoreError>;
    getAgent(id: AgentId): Effect.Effect<Option.Option<AgentInfo>, StoreError>;
    listAgents(threadId: ThreadId): Effect.Effect<ReadonlyArray<AgentInfo>, StoreError>;
    /** Every thread's agents in one read, oldest first, for lists of every thread. */
    readonly listAllAgents: Effect.Effect<ReadonlyArray<AgentInfo>, StoreError>;
    /** Appends atomically: either every event is stored or none is. */
    appendEvents(batch: ReadonlyArray<AgentEvent>): Effect.Effect<void, StoreError>;
    /**
     * An agent's events in order, those after `afterSequence` only when given, and only those of the
     * kinds in `tags` when given: a history's tool output (screenshots and all) is most of it.
     */
    listEvents(
      agentId: AgentId,
      options?: { readonly afterSequence?: number; readonly tags?: ReadonlyArray<EventPayload["_tag"]> },
    ): Effect.Effect<ReadonlyArray<AgentEvent>, StoreError>;
    /** The highest stored sequence for an agent, so a restarted agent continues after it. */
    lastSequence(agentId: AgentId): Effect.Effect<Option.Option<number>, StoreError>;
    /** Every agent's events in a thread, in the order they happened; only the kinds in `tags` when given. */
    listThreadEvents(
      threadId: ThreadId,
      options?: { readonly tags?: ReadonlyArray<EventPayload["_tag"]> },
    ): Effect.Effect<ReadonlyArray<AgentEvent>, StoreError>;
    /** How a tool call in a thread ended, for reading an image of its output on its own. */
    findToolCompletion(
      threadId: ThreadId,
      callId: string,
    ): Effect.Effect<Option.Option<AgentEvent>, StoreError>;
    /** Every thread's events of one kind, in the order they happened. */
    listEventsByTag(tag: EventPayload["_tag"]): Effect.Effect<ReadonlyArray<AgentEvent>, StoreError>;
    /**
     * These agents' completed messages whose text holds `text`, newest first and at most `limit`:
     * finding messages without reading every one.
     */
    listMessagesContaining(
      agentIds: ReadonlyArray<AgentId>,
      text: string,
      limit: number,
    ): Effect.Effect<ReadonlyArray<AgentEvent>, StoreError>;
    /**
     * The usage reported in `[from, to)`, with the events that say which model each turn ran on
     * (these from all time), by agent and in the order they happened.
     */
    listSpendEvents(from: number, to: number): Effect.Effect<ReadonlyArray<SpendEvent>, StoreError>;
    /** How many events of each thread the cloud copy keeps (all but streamed text), by thread id. */
    readonly countSyncedEvents: Effect.Effect<ReadonlyMap<string, number>, StoreError>;
    /**
     * A thread's events the cloud copy keeps, in the order they were stored, from position `offset`
     * on. Stored order never changes within a thread, so positions stay put as events are added.
     */
    listSyncedEvents(
      threadId: ThreadId,
      offset: number,
      limit: number,
    ): Effect.Effect<ReadonlyArray<AgentEvent>, StoreError>;
    /**
     * Marks agents that were live when the app last exited as stopped: their sessions are gone. They
     * keep when they last changed, so a restart doesn't make their threads look new.
     */
    readonly stopLiveAgents: Effect.Effect<void, StoreError>;
    /** Every stored setting by key; the values are whatever was written, undecoded. */
    readonly readSettings: Effect.Effect<Readonly<Record<string, unknown>>, StoreError>;
    /** Stores each given setting atomically, replacing what was there. */
    writeSettings(values: Readonly<Record<string, unknown>>): Effect.Effect<void, StoreError>;
    /** The saved project folders, most recently used first. */
    readonly listProjects: Effect.Effect<ReadonlyArray<StoredProject>, StoreError>;
    /** Saves a project folder, or marks a saved one used at `usedAt`. */
    saveProject(path: string, usedAt: number): Effect.Effect<void, StoreError>;
    /**
     * Stores a project's own setup and run commands, over what its `.cerium.toml` holds (`""` turns
     * one off). Saves the folder as a project if it wasn't one.
     */
    writeProjectScripts(
      path: string,
      scripts: { readonly setup: string | null; readonly run: string | null },
    ): Effect.Effect<void, StoreError>;
    /** Forgets a project folder; its threads keep it. */
    removeProject(path: string): Effect.Effect<void, StoreError>;
  }
>()("cerium/store/Store") {
  /** `migrationsFolder` defaults to the migrations shipped with this package. */
  static layer(options: { readonly filename: string; readonly migrationsFolder?: string }) {
    return Layer.effect(
      Store,
      Effect.gen(function* () {
        const query = <A, E, R>(message: string, effect: Effect.Effect<A, E, R>) =>
          Effect.mapError(effect, (cause) => new StoreError({ message, cause }));

        // Node's built-in `node:sqlite` (no native module to rebuild for Electron) on one connection,
        // which the client hands to one query or transaction at a time. It turns WAL on itself; the
        // connection closes with the layer.
        const client = yield* query(
          `Could not open ${options.filename}`,
          SqliteClient.make({ filename: options.filename }).pipe(Effect.provide(Reactivity.layer)),
        );
        const db = yield* SqliteDrizzle.makeWithDefaults().pipe(
          Effect.provideService(SqliteClient.SqliteClient, client),
        );
        yield* query(
          `Could not open ${options.filename}`,
          Effect.all([
            db.run(sql`PRAGMA synchronous = NORMAL`),
            db.run(sql`PRAGMA foreign_keys = ON`),
            // Full-text search over transcripts depends on FTS5; fail at startup rather than at first search.
            db.run(sql`CREATE VIRTUAL TABLE temp.fts5_probe USING fts5(x)`),
            db.run(sql`DROP TABLE temp.fts5_probe`),
          ]),
        );
        yield* query(
          "Could not migrate the database",
          migrate(db, { migrationsFolder: options.migrationsFolder ?? defaultMigrationsFolder }),
        );
        const decode = <S extends Schema.Top>(schema: S, message: string) => {
          const decodeRow = Schema.decodeUnknownEffect(schema);
          return (row: unknown) =>
            decodeRow(withoutNulls(row)).pipe(Effect.mapError((cause) => new StoreError({ message, cause })));
        };
        const decodeThread = decode(ThreadInfo, "Stored thread is invalid");
        const decodeAgent = decode(AgentInfo, "Stored agent is invalid");
        const decodeEvent = decode(AgentEvent, "Stored event is invalid");

        // Every thread and every agent, as last read, until one is written: lists of every thread are
        // read again after almost every event, for each window, the cloud copy and whether anything
        // works, and decoding each row was most of the time they took.
        const allThreads = remembered(
          query("Could not list threads", db.select().from(threads).orderBy(asc(threads.createdAt))).pipe(
            Effect.flatMap((rows) => Effect.forEach(rows, decodeThread)),
          ),
        );
        const allAgents = remembered(
          query("Could not list agents", db.select().from(agents).orderBy(asc(agents.createdAt))).pipe(
            Effect.flatMap((rows) => Effect.forEach(rows, decodeAgent)),
          ),
        );

        return Store.of({
          createThread: (thread) =>
            query(
              "Could not create the thread",
              db.insert(threads).values({
                ...thread,
                cwd: thread.cwd ?? null,
                worktree: thread.worktree ?? null,
                archivedAt: thread.archivedAt ?? null,
                laterUntil: thread.laterUntil ?? null,
                runId: thread.runId ?? null,
              }),
            ).pipe(allThreads.forget),
          getThread: (id) =>
            query("Could not read the thread", db.select().from(threads).where(eq(threads.id, id))).pipe(
              Effect.flatMap((rows) => Effect.forEach(rows, decodeThread)),
              Effect.map((rows) => Option.fromNullishOr(rows[0])),
            ),
          listThreads: allThreads.read,
          updateThread: (id, patch) =>
            query(
              "Could not update the thread",
              db.update(threads).set(patch).where(eq(threads.id, id)),
            ).pipe(allThreads.forget),
          deleteThread: (id) =>
            query(
              "Could not delete the thread",
              db.transaction((tx) =>
                Effect.all([
                  tx.delete(events).where(eq(events.threadId, id)),
                  tx.delete(agents).where(eq(agents.threadId, id)),
                  tx.delete(threads).where(eq(threads.id, id)),
                ]),
              ),
            ).pipe(allThreads.forget, allAgents.forget),
          // `message_search` is kept by triggers on the events and threads tables (the thread_search
          // migration).
          searchMessages: (typed, { mode, limit }) => {
            const expression = searchExpression(typed);
            if (expression === undefined) return Effect.succeed([]);
            return query(
              "Could not search threads",
              Effect.gen(function* () {
                // Each thread's best-ranked message, then the passage around the match in each.
                const best = yield* db.values<[number, string, number]>(sql`
                SELECT s.rowid, s.thread_id, min(s.rank) AS score
                FROM message_search AS s JOIN threads AS t ON t.id = s.thread_id
                WHERE message_search MATCH ${expression} AND t.mode = ${mode}
                GROUP BY s.thread_id ORDER BY score LIMIT ${limit}`);
                if (best.length === 0) return [];
                // In one query: FTS5 evaluates the match afresh for every query, which a common prefix
                // makes slow, and the backend waits on each.
                const snippets = yield* db.values<[number, string]>(sql`
                SELECT rowid, snippet(message_search, 0, ${MATCH_START}, ${MATCH_END}, '…', 12)
                FROM message_search WHERE message_search MATCH ${expression}
                AND rowid IN (${sql.join(
                  best.map(([rowid]) => sql`${rowid}`),
                  sql`, `,
                )})`);
                const passages = new Map(snippets);
                return best.flatMap(([rowid, threadId]) => {
                  const snippet = passages.get(rowid);
                  return snippet === undefined
                    ? []
                    : [{ threadId: threadId as ThreadId, passage: passageOf(snippet) }];
                });
              }),
            );
          },
          createAgent: (agent) =>
            query(
              "Could not create the agent",
              db.insert(agents).values({
                ...agent,
                parentId: agent.parentId ?? null,
                effort: agent.effort ?? null,
                autoEffort: agent.autoEffort ?? null,
                providerSessionId: agent.providerSessionId ?? null,
              }),
            ).pipe(allAgents.forget),
          updateAgent: (id, patch) =>
            query("Could not update the agent", db.update(agents).set(patch).where(eq(agents.id, id))).pipe(
              allAgents.forget,
            ),
          getAgent: (id) =>
            query("Could not read the agent", db.select().from(agents).where(eq(agents.id, id))).pipe(
              Effect.flatMap((rows) => Effect.forEach(rows, decodeAgent)),
              Effect.map((rows) => Option.fromNullishOr(rows[0])),
            ),
          listAgents: (threadId) =>
            query(
              "Could not list agents",
              db.select().from(agents).where(eq(agents.threadId, threadId)).orderBy(asc(agents.createdAt)),
            ).pipe(Effect.flatMap((rows) => Effect.forEach(rows, decodeAgent))),
          listAllAgents: allAgents.read,
          appendEvents: (batch) =>
            batch.length === 0
              ? Effect.void
              : query(
                  "Could not append events",
                  db.transaction((tx) =>
                    Effect.forEach(
                      batch,
                      (event) =>
                        tx.insert(events).values({
                          id: event.id,
                          threadId: event.threadId,
                          agentId: event.agentId,
                          sequence: event.sequence,
                          at: event.at,
                          tag: event.payload._tag,
                          payload: event.payload,
                          raw: event.raw ?? null,
                        }),
                      { discard: true },
                    ),
                  ),
                ),
          listEvents: (agentId, options) =>
            query(
              "Could not list events",
              db
                .select(eventColumns)
                .from(events)
                .where(
                  and(
                    eq(events.agentId, agentId),
                    options?.afterSequence === undefined
                      ? undefined
                      : gt(events.sequence, options.afterSequence),
                    options?.tags === undefined ? undefined : inArray(events.tag, [...options.tags]),
                  ),
                )
                .orderBy(asc(events.sequence)),
            ).pipe(Effect.flatMap((rows) => Effect.forEach(rows, decodeEvent))),
          lastSequence: (agentId) =>
            query(
              "Could not read the last sequence",
              db
                .select({ last: max(events.sequence) })
                .from(events)
                .where(eq(events.agentId, agentId)),
            ).pipe(Effect.map((rows) => Option.fromNullishOr(rows[0]?.last))),
          listThreadEvents: (threadId, options) =>
            query(
              "Could not list thread events",
              db
                .select(eventColumns)
                .from(events)
                .where(
                  and(
                    eq(events.threadId, threadId),
                    options?.tags === undefined ? undefined : inArray(events.tag, [...options.tags]),
                  ),
                )
                .orderBy(asc(events.at), asc(events.sequence)),
            ).pipe(Effect.flatMap((rows) => Effect.forEach(rows, decodeEvent))),
          findToolCompletion: (threadId, callId) =>
            query(
              "Could not read the tool call",
              db
                .select(eventColumns)
                .from(events)
                .where(
                  and(
                    eq(events.threadId, threadId),
                    // Written out as in `events_tool_call`, so the planner can tell the index covers it.
                    sql`${events.tag} = 'ToolCallCompleted'`,
                    sql`json_extract(${events.payload}, '$.callId') = ${callId}`,
                  ),
                )
                .limit(1),
            ).pipe(
              Effect.flatMap((rows) =>
                rows[0] === undefined ? Effect.succeedNone : Effect.asSome(decodeEvent(rows[0])),
              ),
            ),
          listEventsByTag: (tag) =>
            query(
              "Could not list events",
              db
                .select(eventColumns)
                .from(events)
                .where(eq(events.tag, tag))
                .orderBy(asc(events.at), asc(events.sequence)),
            ).pipe(Effect.flatMap((rows) => Effect.forEach(rows, decodeEvent))),
          listMessagesContaining: (agentIds, text, limit) =>
            agentIds.length === 0
              ? Effect.succeed([])
              : query(
                  "Could not list messages",
                  db
                    .select(eventColumns)
                    .from(events)
                    .where(
                      and(
                        eq(events.tag, "MessageCompleted"),
                        inArray(events.agentId, [...agentIds]),
                        sql`instr(json_extract(${events.payload}, '$.text'), ${text}) > 0`,
                      ),
                    )
                    .orderBy(desc(events.at), desc(events.sequence))
                    .limit(limit),
                ).pipe(Effect.flatMap((rows) => Effect.forEach(rows, decodeEvent))),
          // The fields are read in SQL, and only from the events that hold them: a turn's input can
          // carry attachments, which parsing for a model would read through.
          listSpendEvents: (from, to) =>
            query(
              "Could not read usage",
              db.values<[string, string, number, SpendEvent["tag"], ...Array<string | number | null>]>(sql`
                SELECT agent_id, thread_id, at, tag,
                  CASE WHEN tag IN ('SessionStarted', 'ModelChanged')
                    THEN json_extract(payload, '$.model') END,
                  CASE WHEN tag = 'UsageReported' THEN json_extract(payload, '$.inputTokens') END,
                  CASE WHEN tag = 'UsageReported' THEN json_extract(payload, '$.outputTokens') END,
                  CASE WHEN tag = 'UsageReported' THEN json_extract(payload, '$.cachedInputTokens') END,
                  CASE WHEN tag = 'UsageReported' THEN json_extract(payload, '$.costUsd') END
                FROM events
                WHERE tag IN ('SessionStarted', 'ModelChanged', 'TurnInput')
                  OR (tag = 'UsageReported' AND at >= ${from} AND at < ${to})
                ORDER BY agent_id, sequence`),
            ).pipe(
              Effect.map((rows) =>
                rows.map(([agentId, threadId, at, tag, model, input, output, cached, cost]) => ({
                  agentId: agentId as AgentId,
                  threadId: threadId as ThreadId,
                  at,
                  tag,
                  ...(typeof model === "string" ? { model } : {}),
                  ...(typeof input === "number" ? { inputTokens: input } : {}),
                  ...(typeof output === "number" ? { outputTokens: output } : {}),
                  ...(typeof cached === "number" ? { cachedInputTokens: cached } : {}),
                  ...(typeof cost === "number" ? { costUsd: cost } : {}),
                })),
              ),
            ),
          countSyncedEvents: query(
            "Could not count events",
            db
              .select({ threadId: events.threadId, events: count() })
              .from(events)
              .where(notInArray(events.tag, STREAM_DELTAS))
              .groupBy(events.threadId),
          ).pipe(Effect.map((rows) => new Map(rows.map((row) => [row.threadId, row.events])))),
          // The page is found among the thread's rowids alone, which an index holds: ordering the rows
          // themselves sorted every event of the thread, payloads and all, to skip to the offset.
          listSyncedEvents: (threadId, offset, limit) =>
            query(
              "Could not list thread events",
              db
                .select(eventColumns)
                .from(events)
                .where(
                  inArray(
                    sql`rowid`,
                    db
                      .select({ rowid: sql`rowid` })
                      .from(events)
                      .where(and(eq(events.threadId, threadId), notInArray(events.tag, STREAM_DELTAS)))
                      .orderBy(sql`rowid`)
                      .limit(limit)
                      .offset(offset),
                  ),
                )
                .orderBy(sql`rowid`),
            ).pipe(Effect.flatMap((rows) => Effect.forEach(rows, decodeEvent))),
          stopLiveAgents: query(
            "Could not stop live agents",
            db
              .update(agents)
              .set({ state: "stopped" })
              .where(inArray(agents.state, ["queued", "running", "idle"])),
          ).pipe(allAgents.forget),
          readSettings: query("Could not read settings", db.select().from(settings)).pipe(
            Effect.map((rows) => Object.fromEntries(rows.map((row) => [row.key, row.value]))),
          ),
          writeSettings: (values) => {
            const entries = Object.entries(values);
            return entries.length === 0
              ? Effect.void
              : query(
                  "Could not save settings",
                  db.transaction((tx) =>
                    Effect.forEach(
                      entries,
                      ([key, value]) =>
                        tx
                          .insert(settings)
                          .values({ key, value })
                          .onConflictDoUpdate({ target: settings.key, set: { value } }),
                      { discard: true },
                    ),
                  ),
                );
          },
          listProjects: query(
            "Could not list projects",
            db.select().from(projects).orderBy(desc(projects.usedAt)),
          ),
          saveProject: (path, usedAt) =>
            query(
              "Could not save the project",
              db
                .insert(projects)
                .values({ path, addedAt: usedAt, usedAt, setup: null, run: null })
                .onConflictDoUpdate({ target: projects.path, set: { usedAt } }),
            ),
          writeProjectScripts: (path, scripts) =>
            query(
              "Could not save the project's scripts",
              db
                .insert(projects)
                .values({ path, addedAt: Date.now(), usedAt: Date.now(), ...scripts })
                .onConflictDoUpdate({
                  target: projects.path,
                  set: { setup: scripts.setup, run: scripts.run },
                }),
            ),
          removeProject: (path) =>
            query("Could not remove the project", db.delete(projects).where(eq(projects.path, path))),
        });
      }),
    );
  }
}

/**
 * A read's result, kept until `forget` follows a write that changes it. A read that a write overtakes
 * keeps nothing, so what is kept was read after the last write.
 */
const remembered = <A, E>(fresh: Effect.Effect<A, E>) => {
  let kept: Option.Option<A> = Option.none();
  let writes = 0;
  return {
    read: Effect.suspend(() => {
      if (Option.isSome(kept)) return Effect.succeed(kept.value);
      const before = writes;
      return Effect.tap(fresh, (value) =>
        Effect.sync(() => {
          if (writes === before) kept = Option.some(value);
        }),
      );
    }),
    forget: <B, E2, R>(write: Effect.Effect<B, E2, R>) =>
      Effect.ensuring(
        write,
        Effect.sync(() => {
          writes++;
          kept = Option.none();
        }),
      ),
  };
};

/** SQL NULL columns map to absent optional keys in the protocol schemas. */
const withoutNulls = (row: unknown): unknown =>
  typeof row === "object" && row !== null
    ? Object.fromEntries(Object.entries(row).filter(([, value]) => value !== null))
    : row;
